void app_fill_rect(vanilla_surface_t *surf, int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color)
{
    if (!surf || !surf->pixels || w <= 0 || h <= 0)
        return;

    int32_t surf_w = (int32_t)surf->width;
    int32_t surf_h = (int32_t)surf->height;

    int32_t x0 = x < 0 ? 0 : x;
    int32_t y0 = y < 0 ? 0 : y;
    int32_t x1 = x + w;
    int32_t y1 = y + h;

    if (x1 > surf_w) x1 = surf_w;
    if (y1 > surf_h) y1 = surf_h;

    if (x0 >= x1 || y0 >= y1)
        return;

    uint32_t pitch_px = surf->pitch / sizeof(uint32_t);

    for (int32_t cy = y0; cy < y1; cy++) {
        uint32_t *row = surf->pixels + (size_t)cy * pitch_px;
        for (int32_t cx = x0; cx < x1; cx++) {
            row[cx] = color;
        }
    }
}

void app_draw_rect(vanilla_surface_t *surf, int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color)
{
    if (w <= 0 || h <= 0)
        return;

    app_fill_rect(surf, x, y, w, 1, color);
    app_fill_rect(surf, x, y + h - 1, w, 1, color);
    app_fill_rect(surf, x, y, 1, h, color);
    app_fill_rect(surf, x + w - 1, y, 1, h, color);
}

void app_draw_char(vanilla_surface_t *surf, int32_t x, int32_t y, char c, uint32_t color)
{
    if (!surf || !surf->pixels)
        return;

    uint8_t uc = (uint8_t)c;
    if (uc >= 128)
        uc = '?';

    const uint8_t *bitmap = g_font_8x8[uc];
    uint32_t pitch_px = surf->pitch / sizeof(uint32_t);
    int32_t surf_w = (int32_t)surf->width;
    int32_t surf_h = (int32_t)surf->height;

    for (int32_t r = 0; r < 8; r++) {
        int32_t cy = y + r;
        if (cy < 0 || cy >= surf_h)
            continue;

        uint8_t row = bitmap[r];
        uint32_t *line = surf->pixels + (size_t)cy * pitch_px;

        for (int32_t b = 0; b < 8; b++) {
            int32_t cx = x + b;
            if (cx < 0 || cx >= surf_w)
                continue;

            if (row & (0x80u >> b))
                line[cx] = color;
        }
    }
}

void app_draw_text(vanilla_surface_t *surf, int32_t x, int32_t y, const char *text, uint32_t color)
{
    if (!text)
        return;

    int32_t cur_x = x;
    while (*text) {
        if (*text == '\n') {
            cur_x = x;
            y += 10;
        } else {
            app_draw_char(surf, cur_x, y, *text, color);
            cur_x += 8;
        }
        text++;
    }
}

void app_draw_char_scale(vanilla_surface_t *surf, int32_t x, int32_t y, char c, int scale, uint32_t color)
{
    if (!surf || !surf->pixels || scale <= 0)
        return;

    uint8_t uc = (uint8_t)c;
    if (uc >= 128)
        uc = '?';

    const uint8_t *bitmap = g_font_8x8[uc];
    for (int r = 0; r < 8; r++) {
        uint8_t row = bitmap[r];
        for (int b = 0; b < 8; b++) {
            if (row & (0x80u >> b)) {
                app_fill_rect(surf, x + b * scale, y + r * scale, scale, scale, color);
            }
        }
    }
}

void app_draw_text_scale(vanilla_surface_t *surf, int32_t x, int32_t y, const char *text, int scale, uint32_t color)
{
    if (!text || scale <= 0)
        return;

    int32_t cur_x = x;
    while (*text) {
        if (*text == '\n') {
            cur_x = x;
            y += 8 * scale + 2;
        } else {
            app_draw_char_scale(surf, cur_x, y, *text, scale, color);
            cur_x += 8 * scale;
        }
        text++;
    }
}

void app_draw_button(vanilla_surface_t *surf, int32_t x, int32_t y, int32_t w, int32_t h,
                     const char *text, int is_pressed)
{
    uint32_t bg_col = is_pressed ? APP_COLOR_CARD : APP_COLOR_SURFACE;
    uint32_t border_col = is_pressed ? APP_COLOR_PRIMARY : APP_COLOR_BORDER;
    uint32_t text_col = is_pressed ? APP_COLOR_WHITE : APP_COLOR_TEXT;

    app_fill_rect(surf, x, y, w, h, bg_col);
    app_draw_rect(surf, x, y, w, h, border_col);

    if (text) {
        int len = (int)strlen(text);
        int text_w = len * 8;
        int tx = x + (w - text_w) / 2;
        int ty = y + (h - 8) / 2;
        if (is_pressed) {
            tx++;
            ty++;
        }
        app_draw_text(surf, tx, ty, text, text_col);
    }
}

void app_draw_progress_bar(vanilla_surface_t *surf, int32_t x, int32_t y, int32_t w, int32_t h,
                           int progress_pct, uint32_t bar_color, uint32_t bg_color)
{
    if (progress_pct < 0) progress_pct = 0;
    if (progress_pct > 100) progress_pct = 100;

    app_fill_rect(surf, x, y, w, h, bg_color);
    app_draw_rect(surf, x, y, w, h, APP_COLOR_BORDER);

    int fill_w = ((w - 2) * progress_pct) / 100;
    if (fill_w > 0)
        app_fill_rect(surf, x + 1, y + 1, fill_w, h - 2, bar_color);
}

char app_evdev_to_ascii(uint16_t code, int shift)
{
    if (code >= KEY_1 && code <= KEY_9) {
        static const char num_normal[] = "123456789";
        static const char num_shift[]  = "!@#$%^&*(";
        return shift ? num_shift[code - KEY_1] : num_normal[code - KEY_1];
    }
    if (code == KEY_0)
        return shift ? ')' : '0';

    if (code >= KEY_Q && code <= KEY_P) {
        static const char row1[] = "qwertyuiop";
        char c = row1[code - KEY_Q];
        return shift ? (char)(c - 32) : c;
    }
    if (code >= KEY_A && code <= KEY_L) {
        static const char row2[] = "asdfghjkl";
        char c = row2[code - KEY_A];
        return shift ? (char)(c - 32) : c;
    }
    if (code >= KEY_Z && code <= KEY_M) {
        static const char row3[] = "zxcvbnm";
        char c = row3[code - KEY_Z];
        return shift ? (char)(c - 32) : c;
    }

    switch (code) {
    case KEY_SPACE:      return ' ';
    case KEY_ENTER:      return '\n';
    case KEY_BACKSPACE:  return '\b';
    case KEY_TAB:        return '\t';
    case KEY_MINUS:      return shift ? '_' : '-';
    case KEY_EQUAL:      return shift ? '+' : '=';
    case KEY_LEFTBRACE:  return shift ? '{' : '[';
    case KEY_RIGHTBRACE: return shift ? '}' : ']';
    case KEY_SEMICOLON:  return shift ? ':' : ';';
    case KEY_APOSTROPHE: return shift ? '"' : '\'';
    case KEY_GRAVE:      return shift ? '~' : '`';
    case KEY_BACKSLASH:  return shift ? '|' : '\\';
    case KEY_COMMA:      return shift ? '<' : ',';
    case KEY_DOT:        return shift ? '>' : '.';
    case KEY_SLASH:      return shift ? '?' : '/';
    case KEY_KP0:        return '0';
    case KEY_KP1:        return '1';
    case KEY_KP2:        return '2';
    case KEY_KP3:        return '3';
    case KEY_KP4:        return '4';
    case KEY_KP5:        return '5';
    case KEY_KP6:        return '6';
    case KEY_KP7:        return '7';
    case KEY_KP8:        return '8';
    case KEY_KP9:        return '9';
    case KEY_KPDOT:      return '.';
    case KEY_KPENTER:    return '\n';
    case KEY_KPPLUS:     return '+';
    case KEY_KPMINUS:    return '-';
    case KEY_KPASTERISK: return '*';
    case KEY_KPSLASH:    return '/';
    default:             return 0;
    }
}
