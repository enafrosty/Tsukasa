static inline uint32_t blend_pixel_scalar(uint32_t d, uint32_t s)
{
    uint32_t sa = (s >> 24) & 0xFF;
    if (sa == 0)
        return d;
    if (sa == 255)
        return s;

    uint32_t inv_a = 255 - sa;

    uint32_t sr = (s >> 16) & 0xFF;
    uint32_t sg = (s >> 8) & 0xFF;
    uint32_t sb = s & 0xFF;

    uint32_t dr = (d >> 16) & 0xFF;
    uint32_t dg = (d >> 8) & 0xFF;
    uint32_t db = d & 0xFF;

    uint32_t r = (sr * sa + dr * inv_a + 127) / 255;
    uint32_t g = (sg * sa + dg * inv_a + 127) / 255;
    uint32_t b = (sb * sa + db * inv_a + 127) / 255;

    return (0xFFU << 24) | (r << 16) | (g << 8) | b;
}

static FILE *try_open_cursor_file(const char *assets_dir, const char *name)
{
    char path[512];
    FILE *f = NULL;

    if (assets_dir && assets_dir[0]) {
        snprintf(path, sizeof(path), "%s/%s.argb", assets_dir, name);
        f = fopen(path, "rb");
        if (f) return f;
    }

    snprintf(path, sizeof(path), "assets/cursors/%s.argb", name);
    f = fopen(path, "rb");
    if (f) return f;

    snprintf(path, sizeof(path), "../assets/cursors/%s.argb", name);
    f = fopen(path, "rb");
    if (f) return f;

    snprintf(path, sizeof(path), "../../assets/cursors/%s.argb", name);
    f = fopen(path, "rb");
    if (f) return f;

    snprintf(path, sizeof(path), "/usr/share/cursors/%s.argb", name);
    f = fopen(path, "rb");
    if (f) return f;

    snprintf(path, sizeof(path), "/etc/vanilla/cursors/%s.argb", name);
    f = fopen(path, "rb");
    if (f) return f;

    return NULL;
}

int cursor_manager_init(const char *assets_dir)
{
    int fallback_used = 0;

    for (int i = 0; i < CURSOR_COUNT; i++) {
        const char *name = s_cursor_names[i];
        FILE *f = try_open_cursor_file(assets_dir, name);
        if (!f) {
            if (!s_loaded_pixels[i])
                cursor_init_fallback(i);
            fallback_used = 1;
            continue;
        }

        uint32_t magic = 0;
        uint16_t w = 0, h = 0;
        int16_t hx = 0, hy = 0;

        if (fread(&magic, sizeof(magic), 1, f) != 1 ||
            fread(&w, sizeof(w), 1, f) != 1 ||
            fread(&h, sizeof(h), 1, f) != 1 ||
            fread(&hx, sizeof(hx), 1, f) != 1 ||
            fread(&hy, sizeof(hy), 1, f) != 1) {
            fclose(f);
            if (!s_loaded_pixels[i])
                cursor_init_fallback(i);
            fallback_used = 1;
            continue;
        }

        if ((magic != CURSOR_MAGIC && memcmp(&magic, "CURS", 4) != 0) ||
            w == 0 || w > 32 || h == 0 || h > 32) {
            fclose(f);
            if (!s_loaded_pixels[i])
                cursor_init_fallback(i);
            fallback_used = 1;
            continue;
        }

        if (hx < 0) hx = 0;
        if (hx >= (int16_t)w) hx = (int16_t)w - 1;
        if (hy < 0) hy = 0;
        if (hy >= (int16_t)h) hy = (int16_t)h - 1;

        size_t pixel_bytes = (size_t)w * (size_t)h * sizeof(uint32_t);
        uint32_t *buf = (uint32_t *)malloc(pixel_bytes);
        if (!buf) {
            fclose(f);
            if (!s_loaded_pixels[i])
                cursor_init_fallback(i);
            fallback_used = 1;
            continue;
        }

        if (fread(buf, 1, pixel_bytes, f) != pixel_bytes) {
            free(buf);
            fclose(f);
            if (!s_loaded_pixels[i])
                cursor_init_fallback(i);
            fallback_used = 1;
            continue;
        }

        fclose(f);

        if (s_loaded_pixels[i])
            free(s_loaded_pixels[i]);

        s_loaded_pixels[i] = buf;
        g_cursors[i].pixels = buf;
        g_cursors[i].width = w;
        g_cursors[i].height = h;
        g_cursors[i].hotspot_x = hx;
        g_cursors[i].hotspot_y = hy;
    }

    s_initialized = 1;
    return fallback_used ? -1 : 0;
}

void cursor_manager_destroy(void)
{
    for (int i = 0; i < CURSOR_COUNT; i++) {
        if (s_loaded_pixels[i]) {
            free(s_loaded_pixels[i]);
            s_loaded_pixels[i] = NULL;
        }
        cursor_init_fallback(i);
    }
    s_initialized = 0;
}

const vanilla_cursor_t *cursor_get(vanilla_cursor_shape_t shape)
{
    if (!s_initialized)
        cursor_manager_init("assets/cursors");

    if ((int)shape < 0 || shape >= CURSOR_COUNT)
        shape = CURSOR_ARROW;

    return &g_cursors[shape];
}

void cursor_set_active(vanilla_cursor_shape_t shape)
{
    if ((int)shape < 0 || shape >= CURSOR_COUNT)
        shape = CURSOR_ARROW;
    g_active_shape = shape;
}

vanilla_cursor_shape_t cursor_get_active(void)
{
    return g_active_shape;
}

void cursor_get_rect(int32_t cx, int32_t cy, vanilla_rect_t *out_rect)
{
    if (!out_rect)
        return;

    const vanilla_cursor_t *cur = cursor_get(cursor_get_active());
    out_rect->x = cx - cur->hotspot_x;
    out_rect->y = cy - cur->hotspot_y;
    out_rect->w = cur->width;
    out_rect->h = cur->height;
}

void cursor_render(uint32_t *dst, uint32_t dst_pitch,
                   uint32_t dst_w, uint32_t dst_h,
                   int32_t cx, int32_t cy,
                   const vanilla_rect_t *dirty)
{
    if (!dst || !dirty || dst_w == 0 || dst_h == 0)
        return;

    const vanilla_cursor_t *cur = cursor_get(cursor_get_active());
    if (!cur || !cur->pixels || cur->width == 0 || cur->height == 0)
        return;

    int32_t draw_x = cx - cur->hotspot_x;
    int32_t draw_y = cy - cur->hotspot_y;

    vanilla_rect_t cur_rect = { draw_x, draw_y, (int32_t)cur->width, (int32_t)cur->height };
    vanilla_rect_t vis;
    if (!vanilla_rect_intersect(&cur_rect, dirty, &vis))
        return;

    for (int32_t row = 0; row < cur->height; row++) {
        int32_t py = draw_y + row;
        if (py < 0 || py >= (int32_t)dst_h)
            continue;
        if (py < dirty->y || py >= dirty->y + dirty->h)
            continue;

        for (int32_t col = 0; col < cur->width; col++) {
            int32_t px = draw_x + col;
            if (px < 0 || px >= (int32_t)dst_w)
                continue;
            if (px < dirty->x || px >= dirty->x + dirty->w)
                continue;

            uint32_t src_pixel = cur->pixels[row * cur->width + col];
            uint8_t  src_a = (src_pixel >> 24) & 0xFF;
            if (src_a == 0)
                continue;

            if (src_a == 0xFF) {
                dst[py * dst_pitch + px] = src_pixel;
            } else {
                dst[py * dst_pitch + px] =
                    blend_pixel_scalar(dst[py * dst_pitch + px], src_pixel);
            }
        }
    }
}

vanilla_cursor_shape_t cursor_select_for_hit_region(int32_t px, int32_t py,
                                                    const vanilla_rect_t *win_rect,
                                                    int32_t border_width,
                                                    int32_t titlebar_height)
{
    if (!win_rect) {
        cursor_set_active(CURSOR_ARROW);
        return CURSOR_ARROW;
    }

    if (px < win_rect->x || px >= win_rect->x + win_rect->w ||
        py < win_rect->y || py >= win_rect->y + win_rect->h) {
        cursor_set_active(CURSOR_ARROW);
        return CURSOR_ARROW;
    }

    int32_t edge_threshold = border_width + 4;
    if (edge_threshold < 4)
        edge_threshold = 4;

    int near_left  = (px - win_rect->x)                   < edge_threshold;
    int near_right = (win_rect->x + win_rect->w - 1 - px) < edge_threshold;
    int near_top   = (py - win_rect->y)                   < edge_threshold;
    int near_bot   = (win_rect->y + win_rect->h - 1 - py) < edge_threshold;

    if (near_left && near_right) {
        if ((px - win_rect->x) <= (win_rect->x + win_rect->w - 1 - px))
            near_right = 0;
        else
            near_left = 0;
    }
    if (near_top && near_bot) {
        if ((py - win_rect->y) <= (win_rect->y + win_rect->h - 1 - py))
            near_bot = 0;
        else
            near_top = 0;
    }

    vanilla_cursor_shape_t shape = CURSOR_ARROW;

    if (near_top && near_left)
        shape = CURSOR_RESIZE_NW;
    else if (near_top && near_right)
        shape = CURSOR_RESIZE_NE;
    else if (near_bot && near_left)
        shape = CURSOR_RESIZE_SW;
    else if (near_bot && near_right)
        shape = CURSOR_RESIZE_SE;
    else if (near_left)
        shape = CURSOR_RESIZE_W;
    else if (near_right)
        shape = CURSOR_RESIZE_E;
    else if (near_top)
        shape = CURSOR_RESIZE_N;
    else if (near_bot)
        shape = CURSOR_RESIZE_S;
    else if (py < win_rect->y + titlebar_height)
        shape = CURSOR_ARROW;
    else
        shape = CURSOR_ARROW;

    cursor_set_active(shape);
    return shape;
}
